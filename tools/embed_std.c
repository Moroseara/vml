/*
 * Build tool: embeds the std tree into a C file as
 *   const VMStdSource vm_std_sources[] = { {"json/mod", "source..."}, ... };
 * Keys are paths under std/ without ".vml", so std keeps its folders inside the binary.
 * Usage: embed_std out.c std/a.vml std/b.vml ...
 */
#include <stdio.h>
#include <string.h>

int main(int argc, char **argv) {
    if (argc < 2) {
        fprintf(stderr, "usage: embed_std out.c files...\n");
        return 1;
    }
    FILE *out = fopen(argv[1], "wb");
    if (!out) {
        perror(argv[1]);
        return 1;
    }
    fprintf(out, "/* Generated by tools/embed_std.c from the std .vml files; do not edit. */\n");
    fprintf(out, "#include \"../compiler/module/std_sources.h\"\n\n");
    fprintf(out, "const VMStdSource vm_std_sources[] = {\n");
    for (int i = 2; i < argc; i++) {
        FILE *in = fopen(argv[i], "rb");
        if (!in) {
            perror(argv[i]);
            fclose(out);
            return 1;
        }
        const char *base = argv[i];
        if (strncmp(base, "std/", 4) == 0) base += 4;
        size_t blen = strlen(base);
        if (blen > 4 && strcmp(base + blen - 4, ".vml") == 0) blen -= 4;
        fprintf(out, "    {\"%.*s\",\n     \"", (int)blen, base);
        int c;
        while ((c = fgetc(in)) != EOF) {
            if (c == '\\') fputs("\\\\", out);
            else if (c == '"') fputs("\\\"", out);
            else if (c == '?') fputs("\\?", out);
            else if (c == '\n') fputs("\\n\"\n     \"", out);
            else if (c == '\t') fputs("\\t", out);
            else if (c == '\r') continue;
            else fputc(c, out);
        }
        fclose(in);
        fputs("\"},\n", out);
    }
    fputs("};\n\n", out);
    fprintf(out, "const unsigned vm_std_num_sources = %d;\n", argc - 2);
    fclose(out);
    return 0;
}
